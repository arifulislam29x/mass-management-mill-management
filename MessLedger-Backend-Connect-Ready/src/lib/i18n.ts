export function tDict(lang: Language) {
  return lang === 'bn' ? bn : en;
}

export function formatMoney(amount: number, currency = '৳', lang: Language = 'en'): string {
  const rounded = Math.round((amount + Number.EPSILON) * 100) / 100;
  const formatted = new Intl.NumberFormat(lang === 'bn' ? 'bn-BD' : 'en-US', {
    minimumFractionDigits: Number.isInteger(rounded) ? 0 : 2,
    maximumFractionDigits: 2,
  }).format(rounded);
  return `${currency}${formatted}`;
}

export function formatNum(val: number, lang: Language = 'en', maxDecimals = 2): string {
  const rounded = Math.round((val + Number.EPSILON) * 100) / 100;
  return new Intl.NumberFormat(lang === 'bn' ? 'bn-BD' : 'en-US', {
    minimumFractionDigits: 0,
    maximumFractionDigits: maxDecimals,
  }).format(rounded);
}

export function formatMonthLabel(monthKey: string, lang: Language): string {
  const [yStr, mStr] = monthKey.split('-');
  const year = Number(yStr);
  const monthIdx = Number(mStr) - 1;
  if (!Number.isFinite(year) || monthIdx < 0 || monthIdx > 11) return monthKey;
  const dt = new Date(year, monthIdx, 1);
  return new Intl.DateTimeFormat(lang === 'bn' ? 'bn-BD' : 'en-US', {
    month: 'long',
    year: 'numeric',
  }).format(dt);
}
